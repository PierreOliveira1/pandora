func TestWritingTheSameSkillTwiceChangesNothingTheSecondTime(t *testing.T) {
	env := testEnv(t)
	dir, err := SkillDir(env, ClaudeCode)
	if err != nil {
		t.Fatalf("SkillDir() error = %v", err)
	}
	files := map[string][]byte{
		"SKILL.md":            []byte("# Pandora\n"),
		"services/todoist.md": []byte("# todoist\n"),
	}

	first, err := WriteSkill(context.Background(), env, ClaudeCode, files)
	if err != nil {
		t.Fatalf("WriteSkill() error = %v", err)
	}
	if !first.Changed {
		t.Error("first WriteSkill() Changed = false, want true")
	}
	if first.Method != "file" || first.ConfigPath != dir {
		t.Errorf("result = %+v, want method file and path %s", first, dir)
	}
	if first.BackupPath != "" {
		t.Errorf("BackupPath = %q, want empty", first.BackupPath)
	}
	if got := string(readConfig(t, filepath.Join(dir, "SKILL.md"))); got != "# Pandora\n" {
		t.Errorf("SKILL.md = %q, want the provided content", got)
	}
	if got := string(readConfig(t, filepath.Join(dir, skillMarker))); got != skillMarkerContent {
		t.Errorf("%s = %q, want %q", skillMarker, got, skillMarkerContent)
	}

	before := readConfig(t, filepath.Join(dir, "SKILL.md"))
	second, err := WriteSkill(context.Background(), env, ClaudeCode, files)
	if err != nil {
		t.Fatalf("second WriteSkill() error = %v", err)
	}
	if second.Changed {
		t.Error("second WriteSkill() Changed = true, want false")
	}
	if second.BackupPath != "" {
		t.Errorf("second BackupPath = %q, want empty", second.BackupPath)
	}
	if after := readConfig(t, filepath.Join(dir, "SKILL.md")); !bytes.Equal(after, before) {
		t.Errorf("SKILL.md changed on the second write:\nbefore:\n%s\nafter:\n%s", before, after)
	}
	entries, err := os.ReadDir(filepath.Dir(dir))
	if err != nil {
		t.Fatalf("ReadDir(%q) error = %v", filepath.Dir(dir), err)
	}
	if len(entries) != 1 || entries[0].Name() != "pandora" {
		t.Errorf("skills directory contains %v, want only pandora", entries)
	}
}

func TestAPandoraSkillNotCreatedByPandoraIsNeverOverwritten(t *testing.T) {
	env := testEnv(t)
	dir, err := SkillDir(env, OpenCode)
	if err != nil {
		t.Fatalf("SkillDir() error = %v", err)
	}
	original := "# My own pandora skill\n"
	writeConfig(t, filepath.Join(dir, "SKILL.md"), original, 0o600)

	_, err = WriteSkill(context.Background(), env, OpenCode, map[string][]byte{
		"SKILL.md": []byte("# Generated by Pandora\n"),
	})
	want := "a skill named pandora already exists at " + dir + " and was not created by Pandora; remove or rename it first"
	if err == nil || err.Error() != want {
		t.Fatalf("WriteSkill() error = %v, want %q", err, want)
	}
	if got := string(readConfig(t, filepath.Join(dir, "SKILL.md"))); got != original {
		t.Errorf("SKILL.md = %q, want the original content %q", got, original)
	}
	if _, err := os.Stat(filepath.Join(dir, skillMarker)); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("Stat(%q) error = %v, want no marker", filepath.Join(dir, skillMarker), err)
	}
}

func TestANewSkillVersionReplacesFilesRemovedFromThePreviousOne(t *testing.T) {
	env := testEnv(t)
	dir, err := SkillDir(env, Codex)
	if err != nil {
		t.Fatalf("SkillDir() error = %v", err)
	}

	first, err := WriteSkill(context.Background(), env, Codex, map[string][]byte{
		"SKILL.md":      []byte("version 1\n"),
		"services/x.md": []byte("# x\n"),
	})
	if err != nil || !first.Changed {
		t.Fatalf("first WriteSkill() = %+v, %v; want a change", first, err)
	}
	second, err := WriteSkill(context.Background(), env, Codex, map[string][]byte{
		"SKILL.md":      []byte("version 2\n"),
		"services/y.md": []byte("# y\n"),
	})
	if err != nil || !second.Changed {
		t.Fatalf("second WriteSkill() = %+v, %v; want a change", second, err)
	}

	if _, err := os.Stat(filepath.Join(dir, "services", "x.md")); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("Stat(services/x.md) error = %v, want the old file to be gone", err)
	}
	if got := string(readConfig(t, filepath.Join(dir, "services", "y.md"))); got != "# y\n" {
		t.Errorf("services/y.md = %q, want the new content", got)
	}
	if got := string(readConfig(t, filepath.Join(dir, "SKILL.md"))); got != "version 2\n" {
		t.Errorf("SKILL.md = %q, want the new content", got)
	}
}

func TestAllowingThePandoraCommandKeepsTheUsersOtherPermissions(t *testing.T) {
	t.Run("claude code", func(t *testing.T) {
		env := testEnv(t)
		path := filepath.Join(env.Home, ".claude", "settings.json")
		writeConfig(t, path, `{
  "theme": "dark",
  "permissions": {
    "allow": ["Bash(git status)", "Read"],
    "deny": ["Bash(rm:*)"]
  }
}
`, 0o600)

		res, err := AllowCommand(context.Background(), env, ClaudeCode)
		if err != nil {
			t.Fatalf("AllowCommand() error = %v", err)
		}
		if !res.Changed || res.ConfigPath != path {
			t.Errorf("result = %+v, want a change at %s", res, path)
		}
		if res.BackupPath != path+".pandora.bak" {
			t.Errorf("BackupPath = %q, want %q", res.BackupPath, path+".pandora.bak")
		}

		config := decodeConfig(t, readConfig(t, path))
		if config["theme"] != "dark" {
			t.Errorf("theme = %v, want dark", config["theme"])
		}
		permissions, ok := config["permissions"].(map[string]any)
		if !ok {
			t.Fatalf("permissions = %v, want an object", config["permissions"])
		}
		if want := []any{"Bash(git status)", "Read", "Bash(pandora:*)"}; !reflect.DeepEqual(permissions["allow"], want) {
			t.Errorf("permissions.allow = %v, want %v", permissions["allow"], want)
		}
		if want := []any{"Bash(rm:*)"}; !reflect.DeepEqual(permissions["deny"], want) {
			t.Errorf("permissions.deny = %v, want %v", permissions["deny"], want)
		}

		before := readConfig(t, path)
		second, err := AllowCommand(context.Background(), env, ClaudeCode)
		if err != nil {
			t.Fatalf("second AllowCommand() error = %v", err)
		}
		if second.Changed {
			t.Error("second AllowCommand() Changed = true, want false")
		}
		if second.BackupPath != "" {
			t.Errorf("second BackupPath = %q, want empty", second.BackupPath)
		}
		if after := readConfig(t, path); !bytes.Equal(after, before) {
			t.Errorf("settings changed on the second allow:\nbefore:\n%s\nafter:\n%s", before, after)
		}

		disallowed, err := DisallowCommand(context.Background(), env, ClaudeCode)
		if err != nil {
			t.Fatalf("DisallowCommand() error = %v", err)
		}
		if !disallowed.Changed {
			t.Error("DisallowCommand() Changed = false, want true")
		}
		config = decodeConfig(t, readConfig(t, path))
		permissions = config["permissions"].(map[string]any)
		if want := []any{"Bash(git status)", "Read"}; !reflect.DeepEqual(permissions["allow"], want) {
			t.Errorf("permissions.allow = %v, want %v", permissions["allow"], want)
		}
		if want := []any{"Bash(rm:*)"}; !reflect.DeepEqual(permissions["deny"], want) {
			t.Errorf("permissions.deny = %v, want %v", permissions["deny"], want)
		}
		if config["theme"] != "dark" {
			t.Errorf("theme = %v, want dark", config["theme"])
		}
	})

	t.Run("opencode", func(t *testing.T) {
		env := testEnv(t)
		path := filepath.Join(env.Home, ".config", "opencode", "opencode.json")
		writeConfig(t, path, `{
  "theme": "dark",
  "permission": {
    "bash": "ask",
    "edit": "deny"
  }
}
`, 0o600)

		res, err := AllowCommand(context.Background(), env, OpenCode)
		if err != nil {
			t.Fatalf("AllowCommand() error = %v", err)
		}
		if !res.Changed || res.ConfigPath != path {
			t.Errorf("result = %+v, want a change at %s", res, path)
		}
		if res.BackupPath != path+".pandora.bak" {
			t.Errorf("BackupPath = %q, want %q", res.BackupPath, path+".pandora.bak")
		}

		config := decodeConfig(t, readConfig(t, path))
		if config["theme"] != "dark" {
			t.Errorf("theme = %v, want dark", config["theme"])
		}
		permission, ok := config["permission"].(map[string]any)
		if !ok {
			t.Fatalf("permission = %v, want an object", config["permission"])
		}
		if permission["edit"] != "deny" {
			t.Errorf("permission.edit = %v, want deny", permission["edit"])
		}
		bash, ok := permission["bash"].(map[string]any)
		if !ok {
			t.Fatalf("permission.bash = %v, want an object", permission["bash"])
		}
		if want := map[string]any{"*": "ask", "pandora *": "allow"}; !reflect.DeepEqual(bash, want) {
			t.Errorf("permission.bash = %v, want %v", bash, want)
		}

		before := readConfig(t, path)
		second, err := AllowCommand(context.Background(), env, OpenCode)
		if err != nil {
			t.Fatalf("second AllowCommand() error = %v", err)
		}
		if second.Changed {
			t.Error("second AllowCommand() Changed = true, want false")
		}
		if second.BackupPath != "" {
			t.Errorf("second BackupPath = %q, want empty", second.BackupPath)
		}
		if after := readConfig(t, path); !bytes.Equal(after, before) {
			t.Errorf("config changed on the second allow:\nbefore:\n%s\nafter:\n%s", before, after)
		}

		disallowed, err := DisallowCommand(context.Background(), env, OpenCode)
		if err != nil {
			t.Fatalf("DisallowCommand() error = %v", err)
		}
		if !disallowed.Changed {
			t.Error("DisallowCommand() Changed = false, want true")
		}
		config = decodeConfig(t, readConfig(t, path))
		permission = config["permission"].(map[string]any)
		bash, ok = permission["bash"].(map[string]any)
		if !ok {
			t.Fatalf("permission.bash = %v, want an object after disallow", permission["bash"])
		}
		if want := map[string]any{"*": "ask"}; !reflect.DeepEqual(bash, want) {
			t.Errorf("permission.bash = %v, want %v", bash, want)
		}
		if permission["edit"] != "deny" {
			t.Errorf("permission.edit = %v, want deny", permission["edit"])
		}
		if config["theme"] != "dark" {
			t.Errorf("theme = %v, want dark", config["theme"])
		}
	})
}
